const assert=require('node:assert/strict');
const {describe}=require('../static/evidence.js');
const row={date:'2025-04-01',original_description:'TRANSFER',normalized_description:'TRANSFER',debit:100,credit:0,balance:900,page:1,confidence:.99,suspicious:false,state:'review'};
let result=describe(row);
assert.equal(result.uncertain,false);
assert.match(result.balanceStatus,/does not verify/);
result=describe({...row,state:'approved',reason:'balance mismatch: expected 899.00, difference +1.00'});
assert.equal(result.uncertain,true);assert.equal(result.priority,0);
assert.equal(result.fields.find(f=>f.key==='balance').status,'conflict');
result=describe({...row,_inferred_fields:{debit:{method:'balance delta',original_value:90}}});
assert.equal(result.priority,2);assert.equal(result.fields.find(f=>f.key==='debit').earlierValue,90);
assert.match(result.balanceStatus,/estimated/);
result=describe({...row,counterparty:'AJAY SHARMA',_inferred_fields:{counterparty:{method:'narration reading'}}});
assert.equal(result.uncertain,true);assert.match(result.headline,/name is a guess/);
result=describe({...row,_numeric_candidates:{balance:[{value:900},{value:'900.00'}]}});
assert.equal(result.uncertain,false,'identical numeric values are not disagreements');
result=describe({...row,_numeric_candidates:{balance:[{value:900},{value:990}]}});
assert.equal(result.priority,3);
result=describe({...row,balance:null,debit:null,credit:null,date:null,crop:'ai-table-1.png'});
assert.equal(result.priority,1);assert.match(result.sourceLabel,/Source table/);
assert.match(result.balanceStatus,/could not/);
result=describe({...row,normalized_description:'TRANSFER AJAY',_ai_proposal:{description:'TRANSFER AJAY'},_ocr_before_ai:{original_description:'TRANSFER'}});
assert.equal(result.fields.find(f=>f.key==='normalized_description').earlierValue,'TRANSFER');
assert.equal(result.fields.find(f=>f.key==='normalized_description').status,'ai');
result=describe({...row,reason:'opening balance unavailable; first row not reconciled',suspicious:true});
assert.match(result.balanceStatus,/not reconciled/);
assert.equal(describe({...row,date:'2025-02-30'}).fields.find(f=>f.key==='date').status,'missing');
assert.equal(describe({...row,date:'2025-02-28'}).fields.find(f=>f.key==='date').status,'read');
console.log('PASS: evidence labels preserve uncertainty, estimates, conflicts and source provenance');
